//! Generates `sheet_constants.rs` from `sheets/constants.tsv`.
//!
//! The sheet is the source of truth for every tuning number (Spreadsheet
//! Method: "push constants into sheets, keep logic in kernels"). A malformed
//! row fails the build with its line number. No dependencies, std only.

use std::fmt::Write as _;
use std::path::PathBuf;

const HEADER: [&str; 10] = [
    "id",
    "type",
    "value",
    "unit",
    "kind",
    "confidence",
    "build",
    "used",
    "source",
    "notes",
];
const KINDS: [&str; 4] = ["measured", "sourced", "inferred", "placeholder"];
const CONFIDENCES: [&str; 4] = ["none", "low", "medium", "high"];

fn main() {
    let manifest = PathBuf::from(std::env::var("CARGO_MANIFEST_DIR").unwrap());
    let sheet = manifest.join("../../sheets/constants.tsv");
    println!("cargo:rerun-if-changed={}", sheet.display());

    let text = std::fs::read_to_string(&sheet)
        .unwrap_or_else(|e| panic!("cannot read {}: {e}", sheet.display()));
    let mut lines = text.lines().enumerate();
    let (_, header) = lines.next().expect("constants.tsv is empty");
    let cols: Vec<&str> = header.split('\t').collect();
    assert_eq!(
        cols, HEADER,
        "constants.tsv header must be exactly {HEADER:?}"
    );

    let mut consts = String::new();
    let mut rows = String::new();
    let mut seen = Vec::<String>::new();
    for (i, line) in lines {
        let n = i + 1;
        if line.trim().is_empty() || line.starts_with('#') {
            continue;
        }
        let f: Vec<&str> = line.split('\t').collect();
        let fail = |msg: String| -> ! { panic!("sheets/constants.tsv line {n}: {msg}") };
        if f.len() != HEADER.len() {
            fail(format!(
                "expected {} tab-separated cells, found {}",
                HEADER.len(),
                f.len()
            ));
        }
        let (id, ty, value, unit, kind, conf, build, used, source, notes) =
            (f[0], f[1], f[2], f[3], f[4], f[5], f[6], f[7], f[8], f[9]);
        if id.is_empty()
            || !id
                .chars()
                .all(|c| c.is_ascii_lowercase() || c.is_ascii_digit() || c == '_')
        {
            fail(format!("id {id:?} must be snake_case"));
        }
        if seen.iter().any(|s| s == id) {
            fail(format!("duplicate id {id:?}"));
        }
        seen.push(id.to_owned());
        if !KINDS.contains(&kind) {
            fail(format!("kind {kind:?} not in {KINDS:?}"));
        }
        if !CONFIDENCES.contains(&conf) {
            fail(format!("confidence {conf:?} not in {CONFIDENCES:?}"));
        }
        if used != "yes" && used != "no" {
            fail(format!("used must be yes/no, got {used:?}"));
        }
        if kind != "placeholder" && source.is_empty() {
            fail(format!("{kind} value {id:?} needs a source"));
        }
        let literal = match ty {
            "f32" => {
                let v: f32 = value
                    .parse()
                    .unwrap_or_else(|_| fail(format!("{value:?} is not an f32")));
                if !v.is_finite() {
                    fail(format!("{value:?} is not finite"));
                }
                format!("{v:?}")
            }
            "bool" => match value {
                "true" | "false" => value.to_owned(),
                _ => fail(format!("{value:?} is not a bool")),
            },
            _ => fail(format!("type {ty:?} must be f32 or bool")),
        };
        let name = id.to_ascii_uppercase();
        writeln!(
            consts,
            "/// {unit} · {kind} · confidence {conf} · {build} · {source}"
        )
        .unwrap();
        writeln!(consts, "pub const {name}: {ty} = {literal};").unwrap();
        writeln!(
            rows,
            "    ConstRow {{ id: {id:?}, value: {value:?}, unit: {unit:?}, kind: {kind:?}, confidence: {conf:?}, build: {build:?}, used: {}, source: {source:?}, notes: {notes:?} }},",
            used == "yes"
        )
        .unwrap();
    }

    let out = format!(
        "// @generated by apex-core/build.rs from sheets/constants.tsv. Edit the sheet, not this file.\n\n{consts}\n/// Every sheet row with its provenance.\npub static ROWS: &[ConstRow] = &[\n{rows}];\n"
    );
    let dest = PathBuf::from(std::env::var("OUT_DIR").unwrap()).join("sheet_constants.rs");
    std::fs::write(dest, out).unwrap();
}
